# Topic: Data Types in Python

name = "Sara"
age = 46
marks = 93.4
address = None

print("Name:", name)       # string data type
print("Age:", age)         # integer data type
print("Marks:", marks)     # float data type
print(age >= 18)           # boolean data type
print(address)             # None data type


print(type(name))
print(type(age))
print(type(marks))
print(type(True))
print(type(None))

# Different data types are used to store different types of values in Python.
# Type of value can be checked using type() function.
